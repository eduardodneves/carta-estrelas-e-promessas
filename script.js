const welcomeScreen = document.querySelector("#welcomeScreen");
const enterButton = document.querySelector("#enterButton");
const welcomeHint = document.querySelector("#welcomeHint");
const page = document.querySelector("#page");

const dialog = document.querySelector("#letterDialog");
const letterPaper = document.querySelector("#letterPaper");
const letterView = document.querySelector("#letterView");
const finalView = document.querySelector("#finalView");
const title = document.querySelector("#letterTitle");
const content = document.querySelector("#letterContent");
const scriptureText = document.querySelector("#scriptureText");
const scriptureReference = document.querySelector("#scriptureReference");
const signature = document.querySelector("#letterSignature");
const closeButton = document.querySelector("#closeDialog");
const cardButtons = document.querySelectorAll(".card-hit-area");
const letterCount = document.querySelector("#letterCount");
const letterPercent = document.querySelector("#letterPercent");
const progressFill = document.querySelector("#progressFill");
const previousButton = document.querySelector("#previousLetter");
const nextButton = document.querySelector("#nextLetter");
const revealSurpriseButton = document.querySelector("#revealSurprise");
const backToLetterButton = document.querySelector("#backToLetter");

const music = document.querySelector("#backgroundMusic");
const musicToggle = document.querySelector("#musicToggle");
const musicIcon = document.querySelector("#musicIcon");
const musicLabel = document.querySelector("#musicLabel");
const musicStatus = document.querySelector("#musicStatus");
const volumeControl = document.querySelector("#volumeControl");

let indiceAtual = 0;
let ultimoCartaoAtivado = null;
let musicaTentada = false;

function atualizarControlesDaMusica() {
  if (!music || !musicIcon || !musicLabel) return;

  const tocando = !music.paused;
  musicIcon.textContent = tocando ? "Ⅱ" : "▶";
  musicLabel.textContent = tocando ? "Pausar música" : "Ativar música";
  musicToggle?.setAttribute("aria-label", tocando ? "Pausar música" : "Ativar música");
}

async function iniciarMusica(contexto = "entrada") {
  if (!music) return false;
  if (!music.paused) return true;

  try {
    music.volume = Number(volumeControl?.value ?? 0.52);
    await music.play();
    musicaTentada = true;
    atualizarControlesDaMusica();
    if (musicStatus) musicStatus.textContent = "A melodia está tocando. Aproveite cada palavra.";
    if (welcomeHint) welcomeHint.textContent = "A música começou. Preparei esta surpresa com carinho.";
    return true;
  } catch (erro) {
    musicaTentada = true;
    atualizarControlesDaMusica();
    const bloqueio = erro?.name === "NotAllowedError";
    const mensagem = bloqueio
      ? "Toque em Ativar música para ouvir a melodia."
      : "Não foi possível carregar o MP3. Confira a pasta assets.";
    if (musicStatus) musicStatus.textContent = mensagem;
    if (welcomeHint) welcomeHint.textContent = bloqueio
      ? "Seu navegador pediu mais um toque para liberar o som."
      : "A página abriu, mas não conseguimos carregar a trilha.";
    if (!bloqueio) console.error(`Falha ao iniciar a música (${contexto}):`, erro);
    return false;
  }
}

function entrarNoUniverso() {
  // A chamada play() ocorre diretamente dentro do clique, aproveitando o gesto da visitante.
  iniciarMusica("entrada");
  document.body.classList.add("is-entered");
  page?.removeAttribute("aria-hidden");
  if (page) page.inert = false;
  welcomeScreen?.classList.add("is-leaving");

  window.setTimeout(() => {
    if (welcomeScreen) welcomeScreen.hidden = true;
    cardButtons[0]?.focus({ preventScroll: true });
  }, 950);
}

function atualizarNavegacao() {
  const numeroCarta = indiceAtual + 1;
  const percentual = Math.round((numeroCarta / cartas.length) * 100);
  if (letterCount) letterCount.textContent = `Carta ${numeroCarta} de ${cartas.length}`;
  if (letterPercent) letterPercent.textContent = `${percentual}%`;
  if (progressFill) progressFill.style.width = `${percentual}%`;

  if (previousButton) previousButton.hidden = indiceAtual === 0;
  if (nextButton) nextButton.hidden = indiceAtual === cartas.length - 1;
  if (revealSurpriseButton) revealSurpriseButton.hidden = indiceAtual !== cartas.length - 1;
}

function animarTrocaDeCarta() {
  if (!letterPaper) return;
  letterPaper.classList.remove("is-changing");
  void letterPaper.offsetWidth;
  letterPaper.classList.add("is-changing");
}

function renderizarCarta(indice) {
  const carta = cartas[indice];
  if (!carta || !title || !content || !signature) return;

  indiceAtual = indice;
  title.textContent = carta.titulo;
  content.replaceChildren();

  carta.paragrafos.forEach((texto) => {
    const paragrafo = document.createElement("p");
    paragrafo.textContent = texto;
    content.appendChild(paragrafo);
  });

  scriptureText.textContent = `“${carta.versiculo}”`;
  scriptureReference.textContent = carta.referencia;
  signature.textContent = carta.assinatura;
  atualizarNavegacao();
  animarTrocaDeCarta();
  if (dialog) dialog.scrollTop = 0;
}

function abrirCarta(indice, botaoAtivado) {
  if (!cartas[indice] || !dialog) return;
  ultimoCartaoAtivado = botaoAtivado || null;
  renderizarCarta(indice);
  if (letterView) letterView.hidden = false;
  if (finalView) finalView.hidden = true;
  if (typeof dialog.showModal === "function") {
    if (!dialog.open) dialog.showModal();
  } else {
    dialog.setAttribute("open", "");
  }
}

function mostrarSurpresaFinal() {
  if (!dialog || !letterView || !finalView) return;
  letterView.hidden = true;
  finalView.hidden = false;
  if (dialog) dialog.scrollTop = 0;
  finalView.classList.remove("final-restart");
  void finalView.offsetWidth;
  finalView.classList.add("final-restart");
}

function voltarParaUltimaCarta() {
  if (!letterView || !finalView) return;
  finalView.hidden = true;
  letterView.hidden = false;
  renderizarCarta(cartas.length - 1);
}

function fecharCarta() {
  if (!dialog) return;
  if (typeof dialog.close === "function" && dialog.open) dialog.close();
  else dialog.removeAttribute("open");
}

enterButton?.addEventListener("click", entrarNoUniverso);

cardButtons.forEach((botao) => {
  botao.addEventListener("click", () => {
    // Mesmo se a música tiver sido bloqueada na entrada, este toque poderá iniciá-la.
    if (music?.paused && !musicaTentada) iniciarMusica("primeira-carta");
    abrirCarta(Number(botao.dataset.letter), botao);
  });
  botao.addEventListener("pointerdown", () => botao.classList.add("is-pressed"));
  ["pointerup", "pointerleave", "pointercancel"].forEach((evento) => {
    botao.addEventListener(evento, () => botao.classList.remove("is-pressed"));
  });
});

closeButton?.addEventListener("click", fecharCarta);
previousButton?.addEventListener("click", () => renderizarCarta(Math.max(0, indiceAtual - 1)));
nextButton?.addEventListener("click", () => renderizarCarta(Math.min(cartas.length - 1, indiceAtual + 1)));
revealSurpriseButton?.addEventListener("click", mostrarSurpresaFinal);
backToLetterButton?.addEventListener("click", voltarParaUltimaCarta);

dialog?.addEventListener("click", (evento) => {
  if (evento.target === dialog) fecharCarta();
});
dialog?.addEventListener("close", () => {
  if (ultimoCartaoAtivado) ultimoCartaoAtivado.focus({ preventScroll: true });
});

// Atalho de teclado para percorrer as cartas enquanto a janela está aberta.
dialog?.addEventListener("keydown", (evento) => {
  if (finalView && !finalView.hidden) return;
  if (evento.key === "ArrowRight" && indiceAtual < cartas.length - 1) {
    evento.preventDefault();
    renderizarCarta(indiceAtual + 1);
  } else if (evento.key === "ArrowLeft" && indiceAtual > 0) {
    evento.preventDefault();
    renderizarCarta(indiceAtual - 1);
  }
});

music?.addEventListener("play", atualizarControlesDaMusica);
music?.addEventListener("pause", atualizarControlesDaMusica);
music?.addEventListener("error", () => {
  if (musicStatus) musicStatus.textContent = "Não foi possível carregar o MP3. Confira assets/musica-original.mp3.";
  if (welcomeHint) welcomeHint.textContent = "A música não carregou, mas as cartas estão prontas para você.";
});

musicToggle?.addEventListener("click", async () => {
  if (!music) return;
  if (music.paused) await iniciarMusica("botão de música");
  else {
    music.pause();
    if (musicStatus) musicStatus.textContent = "A música está pausada. Você pode retomá-la quando quiser.";
    atualizarControlesDaMusica();
  }
});

volumeControl?.addEventListener("input", () => {
  if (music) music.volume = Number(volumeControl.value);
});

// Também tenta autoplay ao carregar; se o navegador bloquear, o botão da abertura
// inicia a trilha dentro do gesto da visitante.
if (music) {
  music.volume = Number(volumeControl?.value ?? 0.52);
  iniciarMusica("carregamento inicial");
}

// Parallax discreto apenas em dispositivos com mouse/trackpad.
const movimentoReduzido = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
const possuiMouse = window.matchMedia("(hover: hover) and (pointer: fine)").matches;
if (!movimentoReduzido && possuiMouse) {
  let framePendente = false;
  document.addEventListener("pointermove", (evento) => {
    if (framePendente) return;
    framePendente = true;
    window.requestAnimationFrame(() => {
      const x = (evento.clientX / window.innerWidth - 0.5) * -7;
      const y = (evento.clientY / window.innerHeight - 0.5) * -6;
      document.documentElement.style.setProperty("--parallax-x", `${x.toFixed(2)}px`);
      document.documentElement.style.setProperty("--parallax-y", `${y.toFixed(2)}px`);
      framePendente = false;
    });
  }, { passive: true });
}
